// Strips the document shell off a self-contained playable so it can be
// published as a hosted Artifact, which supplies its own <!doctype>, <html>,
// <head> and <body>. Everything in this repository that runs in a browser is
// one file with no build step, so "building" is deleting four tags.
//
//   node build-artifact.js bonkhorde
//   node build-artifact.js proto3d proto
//
// Output is <dir>/artifact.html and is generated, so it is gitignored.
const fs = require("fs"), path = require("path");
const dirs = process.argv.slice(2);
if (!dirs.length) { console.error("usage: node build-artifact.js <dir> [dir...]"); process.exit(2); }
for (const d of dirs) {
  const src = fs.readFileSync(path.join(__dirname, d, "index.html"), "utf8");
  // EVERY ONE OF THESE IS LOAD-BEARING, and indexOf returns -1 rather than
  // throwing. With </head> missing, head became "<title> .. end of file" and
  // body became "char 5 .. </body>" - so the output was the WHOLE GAME TWICE,
  // 2.2 MB instead of 1.1, and the published page threw "Identifier 'ANIM' has
  // already been declared" from the second copy while the first ran fine. It
  // shipped, because a doubled file is a valid file. A merge that normalises a
  // PUBLISHED artifact back to source is exactly how the two tags go missing -
  // the publish shell supplies them, so they are not in the artifact.
  for (const tag of ["<title>", "</head>", "<body>", "</body>"])
    if (!src.includes(tag))
      throw new Error(`${d}/index.html has no ${tag} - the document shell is broken, ` +
                      `and slicing on a missing tag silently duplicates the file`);
  const head = src.slice(src.indexOf("<title>"), src.indexOf("</head>"));
  const body = src.slice(src.indexOf("<body>") + 6, src.lastIndexOf("</body>"));
  const out  = `<!-- generated by build-artifact.js from ${d}/index.html - do not edit -->\n`
             + head.trim() + "\n" + body.trim() + "\n";
  const dest = path.join(__dirname, d, "artifact.html");
  fs.writeFileSync(dest, out);
  console.log(`${d}/artifact.html  ${(out.length/1024).toFixed(1)} KB`);
}
