// Strips the document shell from index.html so the game can be published as an
// Artifact, which supplies its own <!doctype>/<html>/<head>/<body> wrapper.
// Generated - edit index.html, then re-run: node build-artifact.js
const fs = require("fs");
const src = fs.readFileSync(__dirname + "/index.html", "utf8");
const head = src.slice(src.indexOf("<title>"), src.indexOf("</head>"));
const body = src.slice(src.indexOf("<body>") + 6, src.lastIndexOf("</body>"));
const out  = "<!-- generated by build-artifact.js from index.html - do not edit -->\n"
           + head.trim() + "\n" + body.trim() + "\n";
fs.writeFileSync(__dirname + "/artifact.html", out);
console.log(`artifact.html  ${(out.length/1024).toFixed(1)} KB`);
